//! Embeds `packages/publish/dist` into the binary at compile time.
//!
//! The publish page is served from the loopback origin (ADR-002), which means it has to live
//! *inside* the exe — an installed app cannot serve files out of a source tree, and shipping
//! the page as loose files next to the exe would hand an attacker a writable document root on
//! an origin the user's Google account trusts.
//!
//! **A missing `dist/` is not a build failure.** The Rust workspace must build on a machine
//! that has never run `pnpm build`, so this emits an empty table instead, and
//! `PublishAssets::embedded()` turns that into `PublishError::AssetsMissing` at runtime. The
//! alternative — failing the build — would make every Rust contributor install Node.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

fn main() {
    println!("cargo:rerun-if-changed=build.rs");

    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let dist = manifest
        .join("../../../../packages/publish/dist")
        .canonicalize()
        .ok()
        .filter(|path| path.is_dir());

    let mut entries = Vec::new();
    if let Some(dist) = &dist {
        println!("cargo:rerun-if-changed={}", dist.display());
        collect(dist, dist, &mut entries);
        // Sorted so the generated file is byte-identical across machines; an unsorted
        // `read_dir` would make the crate rebuild for no reason.
        entries.sort();
    }

    let mut generated = String::from(
        "// @generated by build.rs -- do not edit.\n\
         pub(crate) static EMBEDDED: &[(&str, &str, &[u8])] = &[\n",
    );
    for (url_path, disk_path) in &entries {
        writeln!(
            generated,
            "    ({:?}, {:?}, include_bytes!({:?})),",
            url_path,
            mime_for(url_path),
            disk_path
        )
        .expect("writing to a String cannot fail");
    }
    generated.push_str("];\n");

    let out = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR")).join("publish_assets.rs");
    std::fs::write(&out, generated).expect("could not write the generated asset table");
}

fn collect(root: &Path, dir: &Path, out: &mut Vec<(String, String)>) {
    let Ok(read) = std::fs::read_dir(dir) else {
        return;
    };
    for entry in read.flatten() {
        let path = entry.path();
        if path.is_dir() {
            collect(root, &path, out);
        } else if let Ok(relative) = path.strip_prefix(root) {
            // Forward slashes: this becomes a URL path, not a filesystem path.
            let url_path = relative.to_string_lossy().replace('\\', "/");
            out.push((url_path, path.to_string_lossy().into_owned()));
        }
    }
}

/// The `Content-Type` the loopback server will send.
///
/// Guessing wrong here is not cosmetic: a module script served as `text/plain` is refused by
/// the browser outright, and the page renders blank with no network error to point at.
fn mime_for(path: &str) -> &'static str {
    match path.rsplit_once('.').map(|(_, ext)| ext) {
        Some("html") => "text/html; charset=utf-8",
        Some("js" | "mjs") => "text/javascript; charset=utf-8",
        Some("css") => "text/css; charset=utf-8",
        Some("json" | "map") => "application/json; charset=utf-8",
        Some("svg") => "image/svg+xml",
        Some("png") => "image/png",
        Some("jpg" | "jpeg") => "image/jpeg",
        Some("webp") => "image/webp",
        Some("ico") => "image/x-icon",
        Some("woff2") => "font/woff2",
        Some("woff") => "font/woff",
        Some("wasm") => "application/wasm",
        Some("txt") => "text/plain; charset=utf-8",
        _ => "application/octet-stream",
    }
}
